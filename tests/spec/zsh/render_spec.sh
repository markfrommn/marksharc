  End

  guards_case() {
    emulate -L zsh
    ms_fixture
    mkdir -p "$HOME/guard dir"
    : > "$HOME/guard file"
    printf '#!/bin/sh\n' > "$TEST_ROOT/bin/guard-tool"; chmod +x "$TEST_ROOT/bin/guard-tool"
    ms_mod guarded module.conf 'describe "guards"
env BOTH yes when command guard-tool when dir "$HOME/guard dir" when file "$HOME/guard file"
env MISSING no when command no-such-command-xyz
env OS_YES linux-ok when os linux
env OS_NO darwin-no when os darwin
env HOST_YES host-ok when host testhost
env HOST_NO other-no when host otherhost'
    render_cli || { cat "$TEST_ROOT/err"; return 1; }
    local cache="$XDG_CACHE_HOME/marksharc/testhost"
    [[ $(<"$cache/env.zsh") == *'_ms_command_available '\''guard-tool'\'' && _ms_render_dir '* && $(<"$cache/env.zsh") == *' && _ms_render_file '* ]] || { cat "$cache/env.zsh"; return 2; }
    [[ $(<"$cache/env.zsh") != *OS_NO* && $(<"$cache/env.zsh") != *HOST_NO* ]] || { cat "$cache/env.zsh"; return 3; }
    ms_unit "MARKSHARC_SESSION=batch; _ms_env_rebuild=1; source $cache/env.zsh; _ms_rendered_env guarded; print -r -- \"BOTH=\$BOTH OS=\$OS_YES HOST=\$HOST_YES MISSING=\${MISSING-unset}\"" || { cat "$TEST_ROOT/err"; return 4; }
