  golden_case() {
    emulate -L zsh
    ms_fixture
    mkdir -p "$HOME/my tools" "$XDG_CONFIG_HOME/marksharc"
    ms_mod alpha module.conf 'describe "golden"
order 40
env GREETING "two words"
path user "$HOME/my tools"
alias gs "git status"'
    print 'env OVERLAY_VALUE "from overlay"' > "$XDG_CONFIG_HOME/marksharc/config.conf"
    render_cli || { cat "$TEST_ROOT/err"; return 1; }
    local cache="$XDG_CACHE_HOME/marksharc/testhost" id
    [[ -r $cache/render-id && -r $cache/env.zsh ]] || return 2
    id=$(<"$cache/render-id")
    local want="# Generated by marksharc render; do not edit.
# render id: $id
typeset -gA _ms_rendered_modules=( alpha 1 )
typeset -ga _ms_mod_names=( 'alpha' )
typeset -gA _ms_mod_dir=( 'alpha' '$MS_HOME/modules/alpha' )
typeset -gA _ms_mod_req_cmd=(  )
typeset -gA _ms_mod_req_os=(  )
typeset -gA _ms_mod_options=(  )
typeset -gA _ms_mod_optdef=(  )
typeset -g _ms_render_metadata_loaded=1
typeset -ga _ms_rendered_aliases=()
_ms_rendered_env() {
    emulate -L zsh
    case \$1 in
        alpha)
            (( \${_ms_env_rebuild:-1} )) && export GREETING='two words'
            (( \${_ms_env_rebuild:-1} )) && _ms_path_add user '$HOME/my tools'
            [[ \$MARKSHARC_SESSION == interactive ]] && alias gs='git status'
            [[ \$MARKSHARC_SESSION == interactive ]] && _ms_rendered_aliases+=( gs )
            ;;
        overlay)
            (( \${_ms_env_rebuild:-1} )) && export OVERLAY_VALUE='from overlay'
            ;;
    esac
}"
    [[ $(<"$cache/env.zsh") == "$want" ]] || { print -r -- "GOT:\n$(<$cache/env.zsh)\nWANT:\n$want"; return 3; }
  }
  It 'renders a golden env.zsh from module and overlay conf'
    When run golden_case
    The status should be success
  End
End

