# Bash environment entry point. An explicit BASH_ENV can start with no inherited
# MarkSharc variables, so derive the checkout from this entry point in that case.
if [[ -z ${MARKSHARC_HOME-} ]]; then
    MARKSHARC_HOME=${BASH_SOURCE[0]%/core/bash/env.bash}
    export MARKSHARC_HOME
fi
if [[ -n ${MARKSHARC_HOME-} ]]; then
    _ms_bash_host=${HOSTNAME%%.*}
    _ms_bash_cache=${XDG_CACHE_HOME:-$HOME/.cache}/marksharc/$_ms_bash_host
    _ms_bash_context_valid() {
        local context_home='' context_framework='' context_config='' context_id='' render_id='' header='' artifact_id=''
        [[ -r $_ms_bash_cache/bash-context && -r $_ms_bash_cache/render-id && -r $_ms_bash_cache/env.bash ]] || return 1
        {
            IFS= read -r context_home
            IFS= read -r context_framework
            IFS= read -r context_config
            IFS= read -r context_id
        } < "$_ms_bash_cache/bash-context" || return 1
        IFS= read -r render_id < "$_ms_bash_cache/render-id" || return 1
        {
            IFS= read -r header
            IFS= read -r artifact_id
        } < "$_ms_bash_cache/env.bash" || return 1
        [[ $context_home == "$HOME" && $context_framework == "$MARKSHARC_HOME" &&
           $context_config == "${MARKSHARC_CONFIG:-${XDG_CONFIG_HOME:-$HOME/.config}/marksharc}" &&
           $header == '# Generated by marksharc render; do not edit.' &&
           -n $render_id && $context_id == "$render_id" && $artifact_id == "# render id: $render_id" ]]
    }
    _ms_bash_stale_dir() {
        local dir=$1 entry
        [[ -d $dir ]] || return 1
        [[ $dir -nt $_ms_bash_cache/env.bash ]] && return 0
        for entry in "$dir"/*; do
            [[ -e $entry ]] || continue
            [[ $entry -nt $_ms_bash_cache/env.bash ]] && return 0
            if [[ -d $entry && ! -L $entry ]] && _ms_bash_stale_dir "$entry"; then return 0; fi
        done
        return 1
    }
    _ms_bash_refresh_failed=0
    if ! _ms_bash_context_valid ||
       _ms_bash_stale_dir "$MARKSHARC_HOME/core" ||
       _ms_bash_stale_dir "$MARKSHARC_HOME/modules" ||
       _ms_bash_stale_dir "${MARKSHARC_CONFIG:-${XDG_CONFIG_HOME:-$HOME/.config}/marksharc}"; then
        _ms_force_rebuild=1 MARKSHARC_FORCE_BASH_RENDER=1 zsh -f -c 'source "$MARKSHARC_HOME/core/zsh/zshenv.zsh"' >/dev/null 2>&1 || _ms_bash_refresh_failed=1
    fi
    if [[ $_ms_bash_refresh_failed == 0 && -r $MARKSHARC_HOME/core/bash/path.bash ]] && _ms_bash_context_valid &&
       ! _ms_bash_stale_dir "$MARKSHARC_HOME/core" &&
       ! _ms_bash_stale_dir "$MARKSHARC_HOME/modules" &&
       ! _ms_bash_stale_dir "${MARKSHARC_CONFIG:-${XDG_CONFIG_HOME:-$HOME/.config}/marksharc}"; then
        source "$MARKSHARC_HOME/core/bash/path.bash"
        if [[ ${MARKSHARC_MISE_ACTIVATION_PATHS+x} || ${MARKSHARC_MISE_SHIMS+x} || ${MARKSHARC_MISE_SETTINGS_ACTIVE+x} ]]; then
            unset MARKSHARC_ENV MISE_SHELL MISE_NODE_VERSION MISE_GO_VERSION MISE_PYTHON_VERSION MISE_RUBY_VERSION
            unset __MISE_ORIG_PATH __MISE_SESSION __MISE_DIFF
        fi
        _ms_bash_mise_drop_activation_paths
        _ms_bash_mise_drop_shims
        if [[ -n ${MARKSHARC_MISE_SETTINGS_ACTIVE-} ]]; then
            unset MISE_NOT_FOUND_AUTO_INSTALL MISE_GO_SET_GOBIN MISE_IDIOMATIC_VERSION_FILE_ENABLE_TOOLS
        fi
        unset MARKSHARC_MISE_SETTINGS_ACTIVE
        # The renderer writes this host-specific file outside the repository.
        # shellcheck disable=SC1091
        source "$_ms_bash_cache/env.bash"
    fi
    unset -f _ms_bash_context_valid _ms_bash_stale_dir
    unset _ms_bash_host _ms_bash_cache _ms_bash_refresh_failed
fi
true
