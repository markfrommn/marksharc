# This library is shared by BASH_ENV and interactive startup. Keep it Bash 3.2 compatible.
_ms_bash_cache_path() {
    printf '%s/marksharc/%s\n' "${XDG_CACHE_HOME:-$HOME/.cache}" "${HOSTNAME%%.*}"
}

_ms_bash_artifact_matches() {
    local header artifact_id
    [[ -f $1 && -r $1 ]] || return 1
    {
        IFS= read -r header && IFS= read -r artifact_id
    } < "$1" || return 1
    [[ $header == '# Generated by marksharc render; do not edit.' && $artifact_id == "# render id: $2" ]]
}

_ms_bash_context_valid() {
    local cache=$1 context_home context_framework context_config context_id render_id
    [[ -r $cache/bash-context && -r $cache/render-id ]] || return 1
    {
        IFS= read -r context_home &&
        IFS= read -r context_framework &&
        IFS= read -r context_config &&
        IFS= read -r context_id
    } < "$cache/bash-context" || return 1
    IFS= read -r render_id < "$cache/render-id" || return 1
    [[ $context_home == "$HOME" && $context_framework == "$MARKSHARC_HOME" &&
       $context_config == "${MARKSHARC_CONFIG:-${XDG_CONFIG_HOME:-$HOME/.config}/marksharc}" &&
       -n $render_id && $context_id == "$render_id" ]] || return 1
    _ms_bash_artifact_matches "$cache/env.bash" "$render_id" || return 1
    [[ ${2-} != init ]] || _ms_bash_artifact_matches "$cache/init.bash" "$render_id"
}

_ms_bash_stale_dir() {
    local dir=$1 artifact=$2 entry
    [[ -d $dir ]] || return 1
    [[ $dir -nt $artifact ]] && return 0
    for entry in "$dir"/*; do
        [[ -e $entry ]] || continue
        [[ $entry -nt $artifact ]] && return 0
        if [[ -d $entry && ! -L $entry ]] && _ms_bash_stale_dir "$entry" "$artifact"; then return 0; fi
    done
    return 1
}

_ms_bash_env_is_current() {
    _ms_bash_context_valid "$@" &&
        ! _ms_bash_stale_dir "$MARKSHARC_HOME/core" "$1/env.bash" &&
        ! _ms_bash_stale_dir "$MARKSHARC_HOME/modules" "$1/env.bash" &&
        ! _ms_bash_stale_dir "${MARKSHARC_CONFIG:-${XDG_CONFIG_HOME:-$HOME/.config}/marksharc}" "$1/env.bash"
}

_ms_bash_apply_env() {
    local _ms_bash_tracking_env=0 _ms_bash_path_before=$PATH
    # shellcheck source=core/bash/path.bash
    source "$MARKSHARC_HOME/core/bash/path.bash" || return
    if [[ ${MARKSHARC_MISE_ACTIVATION_PATHS+x} || ${MARKSHARC_MISE_SHIMS+x} || ${MARKSHARC_MISE_SETTINGS_ACTIVE+x} ]]; then
        unset MARKSHARC_ENV MISE_SHELL MISE_NODE_VERSION MISE_GO_VERSION MISE_PYTHON_VERSION MISE_RUBY_VERSION
        unset __MISE_ORIG_PATH __MISE_SESSION __MISE_DIFF
    fi
    _ms_bash_mise_drop_activation_paths
    _ms_bash_mise_drop_shims
    if [[ -n ${MARKSHARC_MISE_SETTINGS_ACTIVE-} ]]; then
        unset MISE_NOT_FOUND_AUTO_INSTALL MISE_GO_SET_GOBIN MISE_IDIOMATIC_VERSION_FILE_ENABLE_TOOLS
    fi
    unset MARKSHARC_MISE_SETTINGS_ACTIVE
    # The environment file is generated in the host cache.
    # shellcheck source=/dev/null
    source "$1/env.bash"
}

_ms_bash_prepare_env() {
    local _ms_bash_env_dir _ms_bash_want_artifact=env
    _ms_bash_env_dir=$(_ms_bash_cache_path)
    [[ ${_ms_bash_rc_loading-} != 1 ]] || _ms_bash_want_artifact=init
    if ! _ms_bash_env_is_current "$_ms_bash_env_dir" "$_ms_bash_want_artifact"; then
        _ms_force_rebuild=1 MARKSHARC_FORCE_BASH_RENDER=1 zsh -f -c 'source "$MARKSHARC_HOME/core/zsh/zshenv.zsh"' >/dev/null 2>&1 || return 0
        _ms_bash_env_is_current "$_ms_bash_env_dir" "$_ms_bash_want_artifact" || return 0
    fi
    _ms_bash_apply_env "$_ms_bash_env_dir" || return 0
    if [[ ${_ms_bash_rc_loading-} == 1 ]]; then
        _ms_bash_env_ready=$_ms_bash_env_dir
    fi
}
